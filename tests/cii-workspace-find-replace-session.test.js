import assert from 'node:assert/strict';
import test from 'node:test';

import {
  appendFindReplaceManualRow,
  applyFindReplaceToNewCopy,
  approveAllFindReplaceRows,
  createFindReplaceSession,
  detectFindReplaceCiiVersion,
  qualifyFindReplaceSession,
  replaceFindReplaceManualRows,
  summarizeFindReplaceSession,
  withFindReplaceCsv,
  withFindReplaceMode,
  withFindReplaceTarget,
} from '../tabs/cii-workspace/cii-workspace-find-replace-session.js';

const V14 = `#$ VERSION
    5.00000      14.0000        1256
   Data generated by CAESAR II / Neutral file interface Ver 14.00 12/23
#$ CONTROL
OLD OLD
`;

const V11 = `#$ VERSION
        5.00000      11.0000    1252
#$ CONTROL
OLD
`;

test('v14 session requires Preview then Apply-to-new-copy before download readiness', () => {
  let session = createFindReplaceSession();
  session = withFindReplaceTarget(session, { name: 'model.cii', text: V14 });
  session = withFindReplaceCsv(session, {
    name: 'replace.csv',
    mode: 'DOCUMENT',
    text: 'Find Text,Replace Text\nOLD,NEW\n',
  });

  let summary = summarizeFindReplaceSession(session);
  assert.equal(summary.targetVersion, 14);
  assert.equal(summary.proposed, 1);
  assert.equal(summary.canValidate, false);

  session = approveAllFindReplaceRows(session);
  summary = summarizeFindReplaceSession(session);
  assert.equal(summary.canValidate, true);

  session = qualifyFindReplaceSession(session);
  summary = summarizeFindReplaceSession(session);
  assert.equal(session.status, 'QUALIFIED_PREVIEW');
  assert.equal(summary.qualified, true);
  assert.equal(summary.canApply, false);
  assert.equal(summary.canApplyToNewCopy, true);
  assert.equal(summary.canDownload, false);
  assert.equal(session.qualification.preimage.claims.length, 2);
  assert.match(session.qualification.postimage.target1, /NEW NEW/);

  session = applyFindReplaceToNewCopy(session);
  summary = summarizeFindReplaceSession(session);
  assert.equal(session.status, 'QUALIFIED_PREVIEW');
  assert.equal(summary.canApply, false);
  assert.equal(summary.canApplyToNewCopy, false);
  assert.equal(summary.appliedToNewCopy, true);
  assert.equal(summary.canDownload, true);
  assert.equal(session.release.status, 'APPLIED_TO_NEW_COPY');
  assert.equal(session.release.receipt.originalFileOverwritten, false);
  assert.equal(session.release.receipt.writerInvoked, false);
  assert.equal(session.release.targetHash, session.qualification.postimage.audit.targetHash);
});

test('changing TARGET0 invalidates an applied-to-new-copy release', () => {
  let session = createFindReplaceSession();
  session = withFindReplaceTarget(session, { name: 'model.cii', text: V14 });
  session = withFindReplaceCsv(session, {
    name: 'replace.csv',
    mode: 'DOCUMENT',
    text: 'Find Text,Replace Text\nOLD,NEW\n',
  });
  session = approveAllFindReplaceRows(session);
  session = qualifyFindReplaceSession(session);
  session = applyFindReplaceToNewCopy(session);
  assert.equal(summarizeFindReplaceSession(session).canDownload, true);

  session = withFindReplaceTarget(session, { name: 'model.cii', text: V14.replace('OLD OLD', 'OLD OLD ') });
  const summary = summarizeFindReplaceSession(session);
  assert.equal(session.release, null);
  assert.equal(summary.appliedToNewCopy, false);
  assert.equal(summary.canDownload, false);
  assert.equal(summary.canApply, false);
});

test('non-v14 target fails closed without fallback', () => {
  let session = createFindReplaceSession();
  session = withFindReplaceTarget(session, { name: 'legacy.cii', text: V11 });
  assert.equal(detectFindReplaceCiiVersion(V11), 11);
  assert.equal(session.status, 'TARGET_VERSION_BLOCKED');
  assert.deepEqual(session.errors, ['TARGET_V14_REQUIRED:11']);
});

test('spreadsheet refresh cannot clear a non-v14 target blocker', () => {
  let session = createFindReplaceSession();
  session = withFindReplaceTarget(session, { name: 'legacy.cii', text: V11 });
  session = replaceFindReplaceManualRows(session, [{ findText: 'OLD', replaceText: 'NEW' }]);
  assert.equal(session.status, 'TARGET_VERSION_BLOCKED');
  assert.deepEqual(session.errors, ['TARGET_V14_REQUIRED:11']);
  assert.equal(summarizeFindReplaceSession(session).canValidate, false);
});

test('manual table entry shares CSV contract for qualified displacement block mode', () => {
  let session = createFindReplaceSession();
  session = withFindReplaceMode(session, 'BLOCK');
  session = appendFindReplaceManualRow(session, {
    from: 10,
    to: 20,
    block: 'displacement',
    findText: '500',
    replaceText: '700',
    expectedMatches: 1,
  });
  assert.equal(session.rows.length, 1);
  assert.equal(session.rows[0].scope, 'BLOCK');
  assert.equal(session.rows[0].block, 'DISPLACEMENT');
  assert.equal(session.rows[0].source, 'MANUAL');
  assert.equal(session.rows[0].expectedMatches, 1);
  assert.equal(session.rows[0].status, 'PROPOSED');
});

test('editable spreadsheet replaces manual preview rows instead of duplicating them', () => {
  let session = createFindReplaceSession();
  session = withFindReplaceCsv(session, {
    name: 'replace.csv',
    mode: 'DOCUMENT',
    text: 'Find Text,Replace Text\nOLD,NEW\n',
  });
  session = replaceFindReplaceManualRows(session, [
    { findText: 'AAA', replaceText: 'BBB' },
    { findText: 'CCC', replaceText: 'DDD', expectedMatches: 2 },
  ]);
  assert.equal(session.rows.length, 3);
  assert.deepEqual(session.rows.map((row) => row.source), ['CSV', 'MANUAL', 'MANUAL']);
  assert.equal(session.rows[2].expectedMatches, 2);

  session = replaceFindReplaceManualRows(session, [
    { findText: 'EDITED', replaceText: 'VALUE' },
  ]);
  assert.equal(session.rows.length, 2);
  assert.equal(session.rows[0].source, 'CSV');
  assert.equal(session.rows[0].findText, 'OLD');
  assert.equal(session.rows[1].source, 'MANUAL');
  assert.equal(session.rows[1].findText, 'EDITED');
  assert.equal(session.rows[1].replaceText, 'VALUE');
});

test('manual FORCE entry remains visible but blocked on physical authority', () => {
  let session = createFindReplaceSession();
  session = withFindReplaceMode(session, 'BLOCK');
  session = appendFindReplaceManualRow(session, {
    from: 10,
    to: 20,
    block: 'force',
    findText: '500',
    replaceText: '700',
  });
  assert.equal(session.rows[0].block, 'FORCE');
  assert.equal(session.rows[0].status, 'BLOCKED');
  assert.ok(session.rows[0].blockers.includes('BLOCK_AUTHORITY_NOT_QUALIFIED:FORCE'));
});

test('manual block entry rejects unsupported block authority', () => {
  let session = createFindReplaceSession();
  session = withFindReplaceMode(session, 'BLOCK');
  session = appendFindReplaceManualRow(session, {
    from: 10,
    to: 20,
    block: 'HANGER',
    findText: 'A',
    replaceText: 'B',
  });
  assert.equal(session.rows[0].status, 'BLOCKED');
  assert.ok(session.rows[0].blockers.includes('BLOCK_UNSUPPORTED:HANGER'));
});
