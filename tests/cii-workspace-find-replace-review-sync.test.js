import assert from 'node:assert/strict';
import test from 'node:test';

import { _test as uiTest } from '../tabs/cii-workspace/cii-workspace-find-replace-ui.js';
import {
  createFindReplaceSession,
  decideFindReplaceRow,
  qualifyFindReplaceSession,
  replaceFindReplaceEditorRows,
  summarizeFindReplaceSession,
  withFindReplaceTarget,
} from '../tabs/cii-workspace/cii-workspace-find-replace-session.js';

const V14 = `#$ VERSION\r\n    5.00000      14.0000        1256\r\n   Data generated by CAESAR II / Neutral file interface Ver 14.00 12/23\r\n#$ CONTROL\r\nOLD\r\n`;

test('DOCUMENT editor identity ignores hidden range and block controls', () => {
  const sessionRow = { scope: 'DOCUMENT', findText: 'OLD', rawReplaceText: '/NEW, /ALT', from: null, to: null, block: null };
  const renderedInput = { findText: 'OLD', replaceText: '/NEW, /ALT', from: '', to: '', block: 'NODENAME' };
  assert.equal(uiTest.operationSignature(sessionRow, 'DOCUMENT'), uiTest.operationSignature(renderedInput, 'DOCUMENT'));
});

test('ELEMENT editor identity ignores hidden block but retains range authority', () => {
  const sessionRow = { scope: 'ELEMENT', findText: 'OLD', rawReplaceText: 'NEW', from: 100, to: 110, block: null };
  const renderedInput = { findText: 'OLD', replaceText: 'NEW', from: '100', to: '110', block: 'NODENAME' };
  assert.equal(uiTest.operationSignature(sessionRow, 'ELEMENT'), uiTest.operationSignature(renderedInput, 'ELEMENT'));
  assert.notEqual(uiTest.operationSignature(sessionRow, 'ELEMENT'), uiTest.operationSignature({ ...renderedInput, to: '111' }, 'ELEMENT'));
});

test('BLOCK editor identity still treats block as authoritative', () => {
  const nodename = { findText: 'OLD', replaceText: 'NEW', from: '100', to: '110', block: 'NODENAME' };
  const displacement = { ...nodename, block: 'DISPLACEMENT' };
  assert.notEqual(uiTest.operationSignature(nodename, 'BLOCK'), uiTest.operationSignature(displacement, 'BLOCK'));
});

test('Approve then Validate does not regress to REVIEW_NOT_COMPLETE in DOCUMENT mode', () => {
  let session = withFindReplaceTarget(createFindReplaceSession(), { name: 'target.cii', text: V14 });
  session = replaceFindReplaceEditorRows(session, [{ findText: 'OLD', replaceText: '/NEW, /ALT' }]);
  session = decideFindReplaceRow(session, 1, 'APPROVED');

  const previous = [...session.rows];
  const renderedInputs = [{
    source: 'MANUAL', findText: 'OLD', replaceText: '/NEW, /ALT',
    from: '', to: '', block: 'NODENAME',
  }];
  let next = replaceFindReplaceEditorRows(session, renderedInputs);
  next.rows.forEach((row, index) => {
    const before = previous[index];
    if (before && uiTest.operationSignature(before, session.mode) === uiTest.operationSignature(renderedInputs[index], session.mode)) {
      next = decideFindReplaceRow(next, row.sequence, before.status);
    }
  });

  assert.equal(next.rows[0].status, 'APPROVED');
  assert.equal(summarizeFindReplaceSession(next).canValidate, true);
  const qualified = qualifyFindReplaceSession(next);
  assert.notEqual(qualified.status, 'QUALIFICATION_BLOCKED');
  assert.doesNotMatch(qualified.errors.join(','), /REVIEW_NOT_COMPLETE/);
});
