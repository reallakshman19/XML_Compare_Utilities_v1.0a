import assert from 'node:assert/strict';
import { extractRevisionCompareTransferArchiveBundle, renderRevisionCompareTransferArchiveHtml, REVISION_COMPARE_TRANSFER_ARCHIVE_BOUNDARY, REVISION_COMPARE_TRANSFER_ARCHIVE_TRUST } from '../tabs/revision-compare/revision-transfer-archive-html.js';
import { clone, transferArchiveFixture } from './revision-compare-transfer-archive-fixtures.mjs';
const fixture = await transferArchiveFixture();
const html = renderRevisionCompareTransferArchiveHtml(fixture.workspace.transferCompletion.bundle);
assert.equal(html.startsWith('<!doctype html>\n<html lang="en">'), true);
assert.equal(html.endsWith('\n'), true); assert.equal(html.endsWith('\n\n'), false);
assert.match(html, /default-src 'none'; style-src 'unsafe-inline'; img-src data:; base-uri 'none'; form-action 'none'/);
assert.doesNotMatch(html, /frame-ancestors/);
assert.doesNotMatch(html, /<script(?! id="revision-compare-transfer-handover" type="application\/json")/);
assert.doesNotMatch(html, /https?:\/\//i);
assert.match(html, new RegExp(REVISION_COMPARE_TRANSFER_ARCHIVE_BOUNDARY.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')));
assert.match(html, new RegExp(REVISION_COMPARE_TRANSFER_ARCHIVE_TRUST.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')));
assert.deepEqual(extractRevisionCompareTransferArchiveBundle(html), fixture.workspace.transferCompletion.bundle);
for (const label of ['Complete difference register', 'Complete review register', 'Complete ambiguity-decision register', 'Transfer operations', 'Applied transfer audit', 'Transfer proof invariants', 'Transfer artifact inventory']) assert.match(html, new RegExp(label));
const malicious = clone(fixture.workspace.transferCompletion.bundle);
malicious.payload.evidencePackage.payload.reviewSession.items[0].note = '</script><img src=x onerror=alert(1)>\u2028&';
const hostileHtml = renderRevisionCompareTransferArchiveHtml(malicious);
assert.doesNotMatch(hostileHtml, /<img src=x/);
assert.deepEqual(extractRevisionCompareTransferArchiveBundle(hostileHtml), malicious);
assert.equal(renderRevisionCompareTransferArchiveHtml(fixture.workspace.transferCompletion.bundle), html);
console.log('revision-compare-transfer-archive-html.test.mjs passed');
