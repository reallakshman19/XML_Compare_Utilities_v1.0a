import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const base = new URL('../tabs/sequential-sketcher/scoped-edit/', import.meta.url);
const panel = await readFile(new URL('sequential-component-retirement-request-panel.js', base), 'utf8');
const feature = await readFile(new URL('sequential-component-retirement-request-feature.js', base), 'utf8');
const operations = await readFile(new URL('sequential-component-edit-operations.js', base), 'utf8');
const index = await readFile(new URL('sequential-scoped-edit-index.js', base), 'utf8');
assert.match(panel, /Retirement request preview/);
assert.match(panel, /Whole-component impact only/);
assert.match(panel, /sequentialComponentId|request-component/);
assert.match(panel, /Nothing was published/);
assert.match(feature, /createSequentialEditableTopologySnapshot/);
assert.match(feature, /createSequentialComponentRetirementImpact/);
assert.match(feature, /invalidate/);
assert.match(operations, /retirementPreview\.setActive/);
assert.match(operations, /retirementPreview\.clear/);
assert.match(operations, /retirementPreview\.destroy/);
assert.match(operations, /getRetirementPreview/);
assert.match(index, /sequential-component-retirement-impact-evidence/);
assert.match(index, /sequential-component-retirement-impact-preview/);
assert.doesNotMatch(`${panel}\n${feature}`, /appendTopology|publishTopology|topologyJournal|geometryJournal|applicationService/i);
console.log('sequential component retirement request UI tests: PASS');
