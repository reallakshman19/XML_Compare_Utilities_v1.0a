import assert from 'node:assert/strict';
import fs from 'node:fs';
import test from 'node:test';

import {
  createFindReplaceSession,
  detectFindReplaceCiiVersion,
  withFindReplaceTarget,
} from '../tabs/cii-workspace/cii-workspace-find-replace-session.js';

const V14_WITH_STALE_V11_BANNER = `#$ VERSION \r\n    5.00000      14.0000        1256\r\n  PROJECT: RETAINED HEADER\r\n   Data generated by CAESAR II / Neutral file interface Ver 11.00 04/19\r\n#$ CONTROL \r\n`;

const V11 = `#$ VERSION \r\n    5.00000      11.0000        1256\r\n#$ CONTROL \r\n`;

test('authoritative VERSION record wins over stale generator banner', () => {
  assert.equal(detectFindReplaceCiiVersion(V14_WITH_STALE_V11_BANNER), 14);
  const session = withFindReplaceTarget(createFindReplaceSession(), {
    name: 'stale-banner-v14.CII',
    text: V14_WITH_STALE_V11_BANNER,
  });
  assert.equal(session.target.version, 14);
  assert.equal(session.status, 'TARGET_READY');
  assert.deepEqual(session.errors, []);
});

test('retained Benchmark/T.CII is admitted as CII v14', () => {
  const text = fs.readFileSync(new URL('../Benchmark/T.CII', import.meta.url), 'utf8');
  assert.equal(detectFindReplaceCiiVersion(text), 14);
  const session = withFindReplaceTarget(createFindReplaceSession(), { name: 'T.CII', text });
  assert.equal(session.target.version, 14);
  assert.equal(session.status, 'TARGET_READY');
  assert.deepEqual(session.errors, []);
});

test('v11 remains blocked by the v14-only intake gate', () => {
  assert.equal(detectFindReplaceCiiVersion(V11), 11);
  const session = withFindReplaceTarget(createFindReplaceSession(), { name: 'legacy.CII', text: V11 });
  assert.equal(session.status, 'TARGET_VERSION_BLOCKED');
  assert.deepEqual(session.errors, ['TARGET_V14_REQUIRED:11']);
});
