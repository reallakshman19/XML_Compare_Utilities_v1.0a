import assert from 'node:assert/strict';
import { createPipelineCompletedOutputSession, _test } from '../tabs/pipeline-3d-model/pipeline-3d-model-completed-output-session.js';
import { createPipelineRawReadinessSession } from '../tabs/pipeline-3d-model/pipeline-3d-model-raw-readiness-session.js';
const scan = (value) => Object.freeze({ hasContent: Boolean(value), hasDataRow: /\d/.test(value) });
const readiness = createPipelineRawReadinessSession(scan);
const large = `H\n${'1234567890\t'.repeat(100000)}`;
const raw = { table2a: large, table3a: 'H\n1', table3b: '', table3c: '' };
const firstRaw = readiness.resolve(raw).raw;
const parts = _test.inputIdentityParts({ table1Text: 'T1', profileRaw: firstRaw });
assert.equal(parts.sourceTexts.length, 2);
assert.equal(parts.sourceTexts[1], firstRaw);
let builds = 0;
const output = createPipelineCompletedOutputSession(() => ({ build: ++builds }));
const first = output.resolve({ table1Text: 'T1', profileRaw: firstRaw });
const equalRaw = readiness.resolve({ ...raw }).raw;
assert.equal(equalRaw, firstRaw);
assert.equal(output.resolve({ table1Text: 'T1', profileRaw: equalRaw }), first);
assert.equal(builds, 1);
const changedRaw = readiness.resolve({ ...raw, table3a: 'H\n2' }).raw;
assert.notEqual(changedRaw, firstRaw);
assert.notEqual(output.resolve({ table1Text: 'T1', profileRaw: changedRaw }), first);
assert.equal(builds, 2);
console.log('canonical raw output identity: PASS');
