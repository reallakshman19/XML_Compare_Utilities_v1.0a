# Numeric token finder deliberately accepts adjacent signed values in fixed
# fields (e.g. 5.556000E-01-1.777778E+01).
_NUMBER_RE = re.compile(r"[-+]?(?:\d+(?:\.\d*)?|\.\d+)(?:[EeDd][-+]?\d+)?")


class CiiConversionError(ValueError):
    """Input is not safely convertible under the selected policy."""


@dataclass
class Section:
    name: str
    lines: list[str]


@dataclass
class Audit:
    source_version: int
    target_version: int
    source_sha256: str
    target_sha256: str = ""
    changed_sections: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    loss_events: list[str] = field(default_factory=list)
    source_bytes: int = 0
    target_bytes: int = 0

    def as_dict(self) -> dict[str, object]:
        return {
            "schema": "cii-v11-v14-conversion-audit/v1",
            "source_version": self.source_version,
            "target_version": self.target_version,
            "source_sha256": self.source_sha256,
            "target_sha256": self.target_sha256,
            "source_bytes": self.source_bytes,
            "target_bytes": self.target_bytes,
            "changed_sections": self.changed_sections,
            "warnings": self.warnings,
            "loss_events": self.loss_events,
        }


@dataclass
class ConversionResult:
    data: bytes
    audit: Audit


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _normalise_lines(data: bytes) -> list[str]:
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise CiiConversionError("CII neutral file is not valid UTF-8/ASCII text.") from exc
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    lines = text.split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    return lines


def parse_sections(data: bytes) -> list[Section]:
    lines = _normalise_lines(data)
    sections: list[Section] = []
    current: Section | None = None
    for line_no, raw in enumerate(lines, 1):
        if raw.startswith("#$ "):
            name = raw[3:].strip()
            if not name:
                raise CiiConversionError(f"Blank section name at line {line_no}.")
            current = Section(name=name, lines=[])
            sections.append(current)
            continue
        if current is None:
            if raw.strip():
                raise CiiConversionError(
                    f"Unexpected content before first #$ section at line {line_no}: {raw!r}"
                )
            continue
        current.lines.append(raw)
    if not sections:
        raise CiiConversionError("No #$ sections found in CII neutral file.")
    names = [section.name for section in sections]
    if len(names) != len(set(names)):
        raise CiiConversionError("Duplicate #$ section names are not supported.")
    return sections


def _extract_numbers(line: str) -> tuple[list[float], list[str]] | None:
    matches = list(_NUMBER_RE.finditer(line))
    if not matches:
        return None
    residue_parts: list[str] = []
    cursor = 0
    tokens: list[str] = []
    values: list[float] = []
    for match in matches:
        residue_parts.append(line[cursor:match.start()])
        token = match.group(0)
        tokens.append(token)
        try:
            values.append(float(token.replace("D", "E").replace("d", "e")))
        except ValueError:
            return None
        cursor = match.end()
    residue_parts.append(line[cursor:])
    if any(part.strip() for part in residue_parts):
        return None
    return values, tokens


def _is_float_row(line: str) -> tuple[list[float], list[str]] | None:
    parsed = _extract_numbers(line)
    if parsed is None:
        return None
    values, tokens = parsed
    if not any(("." in token or "e" in token.lower() or "d" in token.lower()) for token in tokens):
        return None
    return values, tokens


def _fmt_v11(value: float) -> str:
    """Mirror the immutable CORE-side six-significant-digit token style."""
    if not math.isfinite(value):
        raise CiiConversionError(f"Non-finite numeric value is not representable: {value!r}")
    magnitude = abs(value)
    if magnitude < 1e-12:
        return "0.000000"
    if magnitude >= 1e9 or magnitude < 0.1:
        return f"{value:.6E}"
    return f"{value:#.6G}"


def _fmt_v14(value: float) -> str:
    if not math.isfinite(value):
        raise CiiConversionError(f"Non-finite numeric value is not representable: {value!r}")
    if abs(value) < 5e-324:
        value = 0.0
    return f"{value:.6E}"


def _row_widths(field_count: int) -> list[int]:
    if field_count <= 0:
        raise CiiConversionError("Numeric row must contain at least one field.")
    return [15] + [13] * (field_count - 1)


def _render_float_row(values: Sequence[float], target: int) -> str:
    formatter = _fmt_v11 if target == 11 else _fmt_v14
    cells = []
    for value, width in zip(values, _row_widths(len(values))):
        token = formatter(value)
        if len(token) > width:
            raise CiiConversionError(
                f"Numeric token {token!r} exceeds fixed field width {width}."
            )
        cells.append(token.rjust(width))
    return "".join(cells)


def _numeric_row_expected_width(field_count: int) -> int:
    return 15 + 13 * (field_count - 1)


def _token_is_real_literal(token: str) -> bool:
    """Return True when a numeric token is lexically a REAL rather than INTEGER.

    CAESAR neutral records can mix I13 and G13.6 fields on one physical line.
    Re-rendering such a line as an all-REAL row changes integer fields like
    ``0`` into ``0.000000`` and violates the FORTRAN input contract.  The
    lexical distinction is therefore structural evidence, not formatting noise.
    """
    lowered = token.lower()
    return "." in token or "e" in lowered or "d" in lowered


def _generic_numeric_convert(line: str, target: int) -> str:
    parsed = _is_float_row(line)
    if parsed is None:
        return line
    values, tokens = parsed

    # Never reinterpret a mixed I/G fixed record as an all-REAL row.  Known
    # examples include the MISCEL_1 execution options and hanger defaults.
    # Their numeric widths are compatible across the qualified generations, so
    # preserving the source record byte-for-byte is safer than destroying the
    # integer field grammar merely to change floating-point presentation.
    token_kinds = {_token_is_real_literal(token) for token in tokens}
    if len(token_kinds) > 1:
        return line

    # Fixed-format all-REAL numeric rows are 15 + 13*(n-1).  Permit source lines
    # with trailing blanks, but do not reinterpret arbitrary short/long text.
    expected = _numeric_row_expected_width(len(values))
    if len(line.rstrip()) > expected or len(line) < expected:
        return line
    return _render_float_row(values, target)
